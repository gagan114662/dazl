// Stripe test mode end to end down to the plan limit on the next scan (test/helpers/billing-limits-runtime.mts). Real
// routes in their own process; signed fixture events; Stripe stubbed; the scan runner never starts.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

test('checkout -> webhook -> plan -> limits on the next scan; failed payment past_due; cancel -> Free', () => {
  const env = { ...process.env }; delete env.NODE_TEST_CONTEXT
  const r = spawnSync(process.execPath, ['--experimental-strip-types', '--no-warnings', '--import', './test/helpers/net-fence.ts',
    '--loader', './test/helpers/health-route-loader.mjs', '--test', './test/helpers/billing-limits-runtime.mts'],
  { cwd: fileURLToPath(new URL('../', import.meta.url)), env, encoding: 'utf8', timeout: 120000 })
  assert.equal(r.error, undefined, String(r.error))
  assert.equal(r.status, 0, r.stdout + r.stderr)
  assert.match(r.stdout, /BILLING_LIMITS_OK/)
})
