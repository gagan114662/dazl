// Mechanical SQLite DDL -> Postgres DDL translator. FAILS LOUD on any
// construct it does not know how to translate - a silent drop is worse than
// no translation. Input: sqlite_master dump from extract-schema.ts (the
// authoritative post-migration schema produced by the app's own code).
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(process.env.SQLITE_SCHEMA || '/tmp/full-schema.sql', 'utf8')
const out = process.env.PG_SCHEMA_OUT || '/tmp/full-schema-pg.sql'

// Split: triggers contain semicolons inside BEGIN...END, so pull them out first.
const triggerRe = /CREATE TRIGGER (?:IF NOT EXISTS )?(\w+)\s+BEFORE (INSERT|UPDATE(?: OF \w+)?) ON (\w+)\s+WHEN ([\s\S]*?)\s+BEGIN SELECT RAISE\(ABORT, '([^']*)'\); END;/g
const triggers: { name: string; event: string; table: string; when: string; msg: string }[] = []
let rest = src.replace(triggerRe, (_m, name, event, table, when, msg) => {
  triggers.push({ name, event, table: table as string, when: when as string, msg: msg as string })
  return ''
})
if (/CREATE TRIGGER/i.test(rest)) throw new Error('untranslated trigger shape remains - extend the translator')

const stmts = rest.split(/;\s*\n/).map(s => s.trim()).filter(Boolean)
const translated: string[] = []
const problems: string[] = []

for (let s of stmts) {
  const orig = s
  s = s.replace(/CAST\(strftime\('%s','now'\) AS INTEGER\)/g, 'CAST(extract(epoch from now()) AS INTEGER)')
  s = s.replace(/strftime\('%s','now'\)/g, 'extract(epoch from now())')
  s = s.replace(/unixepoch\(\)/g, 'extract(epoch from now())')
  s = s.replace(/\blength\(/g, 'char_length(')
  s = s.replace(/\bINTEGER\b/g, 'BIGINT')
  s = s.replace(/CREATE TABLE IF NOT EXISTS/g, 'CREATE TABLE IF NOT EXISTS')
  // Loud-fail on anything sqlite-only that survived.
  const bad = s.match(/unixepoch|strftime|AUTOINCREMENT|\bRAISE\(|PRAGMA|json_extract|randomblob|GLOB\b/i)
  if (bad) { problems.push(`${orig.slice(0, 80)}... [surviving token: ${bad[0]}]`); continue }
  translated.push(s)
}
// FK-aware ordering: PG requires the referenced table to exist first.
const isTable = (st: string) => /^CREATE TABLE/.test(st)
const tableName = (st: string) => st.match(/^CREATE TABLE (\w+)/)![1]
const refs = (st: string) => [...st.matchAll(/REFERENCES (\w+)/g)].map(m => m[1])
const tableStmts = translated.filter(isTable)
const otherStmts = translated.filter(st => !isTable(st))
const remaining = new Map(tableStmts.map(st => [tableName(st), st]))
const ordered: string[] = []
let progress = true
while (remaining.size && progress) {
  progress = false
  for (const [name, st] of [...remaining]) {
    if (refs(st).every(r => !remaining.has(r) || r === name)) {
      ordered.push(st); remaining.delete(name); progress = true
    }
  }
}
if (remaining.size) {
  console.error('TRANSLATION FAILED - FK cycle or missing table among: ' + [...remaining.keys()].join(', '))
  process.exit(1)
}
translated.length = 0
translated.push(...ordered, ...otherStmts)

if (problems.length) {
  console.error('TRANSLATION FAILED - untranslatable statements:')
  for (const p of problems) console.error('  ' + p)
  process.exit(1)
}

// Triggers -> PG functions. WHEN clause becomes an IF guard in the body so
// subqueries (leads_only_while_running) are legal, which PG trigger WHEN
// clauses do not allow.
const pgTriggers: string[] = []
for (const t of triggers) {
  let cond = t.when.replace(/\bIS NOT\b/g, 'IS DISTINCT FROM')
  const ev = t.event.startsWith('UPDATE OF') ? `UPDATE OF ${t.event.slice(10)}` : t.event
  pgTriggers.push(`
CREATE OR REPLACE FUNCTION dazl_guard_${t.name}() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (${cond}) THEN RAISE EXCEPTION '${t.msg}'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS ${t.name} ON ${t.table};
CREATE TRIGGER ${t.name} BEFORE ${ev} ON ${t.table} FOR EACH ROW EXECUTE FUNCTION dazl_guard_${t.name}();`)
}

// Idempotent re-apply: drop everything this script creates, then recreate.
const tables = [...src.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?(\w+)/g)].map(m => m[1])
const header = `-- GENERATED by translate-schema.ts from the app's own sqlite migrations.
-- ${tables.length} tables, ${translated.length - tables.length - triggers.length * 0} non-table statements, ${triggers.length} triggers.
-- Type mapping: INTEGER -> BIGINT (epoch seconds overflow int4 in 2038).
DROP TABLE IF EXISTS ${tables.join(', ')} CASCADE;

`
writeFileSync(out, header + translated.join(';\n\n') + ';\n' + pgTriggers.join('\n') + '\n')
console.log(`translated: ${translated.length} statements (${tables.length} tables), ${triggers.length} triggers -> functions`)
