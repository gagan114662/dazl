-- Captured production scan traces (lib/evals/capture.ts, docs/design/agent-evals.md "Production capture"): one redacted
-- trace per captured run attempt, tenant-scoped. Retention hold: rows are deleted only under an explicit valid
-- DAZL_TRACE_RETENTION_DAYS (capture on alone never purges). Capture is OFF unless DAZL_TRACE_CAPTURE=1. Renumbered
-- 0025 -> 0040 on the port onto main 765dfac0 (next after 0039_tenant_lifecycle).
CREATE TABLE scan_traces (
      id TEXT PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      job_id TEXT NOT NULL,
      attempt BIGINT NOT NULL,
      created_at BIGINT NOT NULL,
      bytes BIGINT NOT NULL,
      trace TEXT NOT NULL
    );
CREATE INDEX scan_traces_created ON scan_traces (created_at);
CREATE INDEX scan_traces_tenant ON scan_traces (tenant_id, created_at);

-- Tenant-lifecycle guards for the new tenant-scoped table, generated by the same extract/translate pipeline as
-- 0039 (guardTriggers over the live sqlite schema): a tombstoned tenant can neither gain nor keep trace rows.

CREATE OR REPLACE FUNCTION dazl_guard_tomb_scan_traces() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock_shared(hashtext(NEW.tenant_id));
  IF (EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = NEW.tenant_id)) THEN RAISE EXCEPTION 'tenant deleted'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tomb_scan_traces ON scan_traces;
CREATE TRIGGER tomb_scan_traces BEFORE INSERT ON scan_traces FOR EACH ROW EXECUTE FUNCTION dazl_guard_tomb_scan_traces();

CREATE OR REPLACE FUNCTION dazl_guard_tomb_upd_scan_traces() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock_shared(hashtext(NEW.tenant_id));
  PERFORM pg_advisory_xact_lock_shared(hashtext(OLD.tenant_id));
  IF (NEW.tenant_id IS DISTINCT FROM OLD.tenant_id AND ((EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = NEW.tenant_id)) OR (EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = OLD.tenant_id)))) THEN RAISE EXCEPTION 'tenant deleted'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tomb_upd_scan_traces ON scan_traces;
CREATE TRIGGER tomb_upd_scan_traces BEFORE UPDATE OF tenant_id ON scan_traces FOR EACH ROW EXECUTE FUNCTION dazl_guard_tomb_upd_scan_traces();
