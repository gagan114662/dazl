-- Durable audit trail (lib/audit.ts): append-only events per workspace. UPDATE is refused; DELETE is refused except
-- inside the retention purge's transaction, while its audit_purge_gate row exists. TRUNCATE (which row triggers do not
-- see) is refused outright: the purge deletes rows, it never truncates.
CREATE TABLE audit_events (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    actor_id TEXT NOT NULL CHECK (char_length(actor_id) <= 80),
    actor_kind TEXT NOT NULL CHECK (actor_kind IN ('user', 'service', 'support')),
    action TEXT NOT NULL CHECK (char_length(action) <= 64),
    resource_type TEXT NOT NULL CHECK (char_length(resource_type) <= 40),
    resource_id TEXT CHECK (resource_id IS NULL OR char_length(resource_id) <= 80),
    decision TEXT NOT NULL CHECK (decision IN ('allowed', 'denied')),
    summary TEXT NOT NULL DEFAULT '{}' CHECK (char_length(summary) <= 2000),
    correlation_id TEXT CHECK (correlation_id IS NULL OR char_length(correlation_id) <= 80),
    at BIGINT NOT NULL,
    seq BIGINT NOT NULL
  );

CREATE TABLE audit_purge_gate (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1));

CREATE INDEX audit_events_seq ON audit_events (seq);

CREATE INDEX audit_events_at ON audit_events (at);

CREATE INDEX audit_events_tenant_at ON audit_events (tenant_id, at);

CREATE OR REPLACE FUNCTION dazl_guard_audit_events_no_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM audit_purge_gate)) THEN RAISE EXCEPTION 'audit events are append-only'; END IF;
  RETURN OLD;
END $$;
DROP TRIGGER IF EXISTS audit_events_no_delete ON audit_events;
CREATE TRIGGER audit_events_no_delete BEFORE DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION dazl_guard_audit_events_no_delete();

CREATE OR REPLACE FUNCTION dazl_guard_audit_events_no_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (TRUE) THEN RAISE EXCEPTION 'audit events are append-only'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS audit_events_no_update ON audit_events;
CREATE TRIGGER audit_events_no_update BEFORE UPDATE ON audit_events FOR EACH ROW EXECUTE FUNCTION dazl_guard_audit_events_no_update();

-- PG only (SQLite has no TRUNCATE): row triggers do not fire on TRUNCATE, so it gets a statement trigger of its own.
CREATE OR REPLACE FUNCTION dazl_guard_audit_events_no_truncate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit events are append-only';
END $$;
DROP TRIGGER IF EXISTS audit_events_no_truncate ON audit_events;
CREATE TRIGGER audit_events_no_truncate BEFORE TRUNCATE ON audit_events FOR EACH STATEMENT EXECUTE FUNCTION dazl_guard_audit_events_no_truncate();
