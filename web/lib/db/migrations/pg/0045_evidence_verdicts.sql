-- Independent evidence verifier (#395; lib/verifier/, docs/design/evidence-verifier.md): one tenant-scoped row per
-- verification run. Written 'running' with the run's budget reserved, completed once with its verdict and full versioned
-- record (blinded claim, the verifier's own source snapshots, judge samples, budget, log); final once done (trigger).
-- Erased with its tenant; no retention purge is defined. Numbered after #385's 0044 (claim file: 0045 i395 #395).
CREATE TABLE evidence_verdicts (
      id TEXT PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      claim_hash TEXT NOT NULL CHECK (char_length(claim_hash) = 64),
      verifier_version TEXT NOT NULL CHECK (char_length(verifier_version) <= 40),
      state TEXT NOT NULL CHECK (state IN ('running', 'done')),
      verdict TEXT CHECK (verdict IS NULL OR verdict IN ('pass', 'fail', 'unknown')),
      action TEXT CHECK (action IS NULL OR action IN ('accept', 'hold', 'skip')),
      day TEXT NOT NULL CHECK (char_length(day) = 10),
      reserved_micros BIGINT NOT NULL CHECK (reserved_micros >= 0),
      spent_micros BIGINT CHECK (spent_micros IS NULL OR spent_micros >= 0),
      created_at BIGINT NOT NULL,
      finished_at BIGINT,
      record TEXT CHECK (record IS NULL OR char_length(record) <= 2000000)
    );

CREATE INDEX evidence_verdicts_tenant_claim ON evidence_verdicts (tenant_id, claim_hash, created_at);

CREATE INDEX evidence_verdicts_tenant_day ON evidence_verdicts (tenant_id, day);

CREATE OR REPLACE FUNCTION dazl_guard_evidence_verdicts_final() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (OLD.state = 'done') THEN RAISE EXCEPTION 'evidence verdicts are final once done'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS evidence_verdicts_final ON evidence_verdicts;
CREATE TRIGGER evidence_verdicts_final BEFORE UPDATE ON evidence_verdicts FOR EACH ROW EXECUTE FUNCTION dazl_guard_evidence_verdicts_final();

-- Tenant-lifecycle guards for the new tenant-scoped table, generated by the same extract/translate pipeline as 0039
-- (guardTriggers over the live sqlite schema): a tombstoned tenant can neither gain nor keep verdict rows.

CREATE OR REPLACE FUNCTION dazl_guard_tomb_evidence_verdicts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock_shared(hashtext(NEW.tenant_id));
  IF (EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = NEW.tenant_id)) THEN RAISE EXCEPTION 'tenant deleted'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tomb_evidence_verdicts ON evidence_verdicts;
CREATE TRIGGER tomb_evidence_verdicts BEFORE INSERT ON evidence_verdicts FOR EACH ROW EXECUTE FUNCTION dazl_guard_tomb_evidence_verdicts();

CREATE OR REPLACE FUNCTION dazl_guard_tomb_upd_evidence_verdicts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock_shared(hashtext(NEW.tenant_id));
  PERFORM pg_advisory_xact_lock_shared(hashtext(OLD.tenant_id));
  IF (NEW.tenant_id IS DISTINCT FROM OLD.tenant_id AND ((EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = NEW.tenant_id)) OR (EXISTS (SELECT 1 FROM tenant_tombstones WHERE deleted_tenant = OLD.tenant_id)))) THEN RAISE EXCEPTION 'tenant deleted'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tomb_upd_evidence_verdicts ON evidence_verdicts;
CREATE TRIGGER tomb_upd_evidence_verdicts BEFORE UPDATE OF tenant_id ON evidence_verdicts FOR EACH ROW EXECUTE FUNCTION dazl_guard_tomb_upd_evidence_verdicts();
