-- Free-trial spend caps (lib/billing/trial-budget.ts): one reservation per admitted trial scan, counted against the
-- per-account and global daily ceilings (settled_at: when the scan's last paid step ended), and the single row every admission locks (created by the first one) so two instances
-- admit one at a time.
CREATE TABLE trial_budget_lock (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1), n BIGINT NOT NULL DEFAULT 0);

CREATE TABLE trial_reservations (
      id          TEXT PRIMARY KEY,
      tenant_id   TEXT NOT NULL,
      job_id      TEXT,
      reserve_usd DOUBLE PRECISION NOT NULL CHECK (reserve_usd > 0),
      day         BIGINT NOT NULL,
      created_at  BIGINT NOT NULL,
      settled_at  BIGINT
    );
CREATE INDEX trial_reservations_day ON trial_reservations (day, tenant_id);
